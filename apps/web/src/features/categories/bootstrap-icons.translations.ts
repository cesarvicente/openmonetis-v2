/**
 * Dicionário português dos nomes e tags em inglês do Bootstrap Icons.
 * Cada linha é `inglês=tradução|sinônimo|sinônimo`; a primeira tradução compõe o nome exibido e
 * todas entram na busca. Termos iguais nos dois idiomas e marcas não precisam de entrada.
 */
function parseDictionary(source: string): ReadonlyMap<string, string[]> {
  return new Map(
    source
      .trim()
      .split("\n")
      .map((line) => {
        const [term, translations] = line.trim().split("=") as [string, string];
        return [term, translations.split("|")] as const;
      }),
  );
}

